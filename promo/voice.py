"""Озвучка ролика (RHVoice, офлайн): по одному wav на сцену + timings.json с длительностью сцен.
python voice.py <outdir>"""
import json, subprocess, sys, wave
out = sys.argv[1]
VOICE = "aleksandr-hq"
PAD = 0.55  # пауза после фразы, сек
LINES = {
    "intro":    "Сигналы по золоту прямо в Телеграм. Знакомься: бот Икс Эй Ю Голд.",
    "signal":   "Бот следит за рынком золота каждые пятнадцать секунд. Как только появляется сетап, он сам присылает сигнал с графиком: точка входа, стоп-лосс и тейк-профит.",
    "strats":   "Сигналы дают семь стратегий: откат по Эр Эс Ай, пробой канала, ордер-блоки и Эф Ви Джи, снятие ликвидности и другие. Каждую проверили на истории золота за последние три года.",
    "rr":       "В каждой сделке риск к прибыли один к двум. Стоп сто пипсов, цель двести.",
    "lot":      "Укажи свой капитал, и бот сам рассчитает лот под твой депозит.",
    "calendar": "Календарь новостей США с прогнозами. Бот заранее предупреждает о важных новостях и объясняет, как они повлияют на доллар и золото.",
    "features": "Каждое утро разбор рынка. После каждой сделки отчёт со статистикой. И всё это на русском, узбекском или английском.",
    "price":    "Три дня бесплатно. Дальше тысяча звёзд за десять дней, оплата Телеграм Старс прямо в боте.",
    "cta":      "Пиши боту в Телеграм. Форекс Си Эф Ди бот. Помни, торговля связана с риском.",
}
timings = []
for key, text in LINES.items():
    path = f"{out}/v_{key}.wav"
    subprocess.run(["RHVoice-test", "-p", VOICE, "-r", "108", "-o", path], input=text.encode(), check=True)
    with wave.open(path) as w:
        d = w.getnframes() / w.getframerate()
    timings.append({"key": key, "voice": round(d, 3), "dur": round(d + PAD + (0.5 if key == "intro" else 0), 3)})
json.dump(timings, open(f"{out}/timings.json", "w"), indent=1)
print(json.dumps(timings), sum(t["dur"] for t in timings))
